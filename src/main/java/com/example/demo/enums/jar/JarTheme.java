package com.example.demo.enums.jar;

public enum JarTheme {
    /*
     * 봄 테마
     * - 기존 "커플 추억" 역할
     * - 분홍, 빨강, 벚꽃 느낌
     */
    SPRING,

    /*
     * 여름 테마
     * - 기존 "가족 추억" 역할
     * - 초록, 햇살, 싱그러운 느낌
     */
    SUMMER,

    /*
     * 가을 테마
     * - 새로 추가되는 테마
     * - 주황, 갈색, 단풍 느낌
     */
    AUTUMN,

    /*
     * 겨울 테마
     * - 기존 "친구 우정" 역할
     * - 파랑, 하양, 눈 느낌
     */
    WINTER,

    /*
     * 라벤더 테마
     * - 기존 "직접 만든 저금통" 역할
     * - 보라, 라벤더, 차분한 느낌
     */
    LAVENDER,

    /*
     * 숲 테마
     * - 새로 추가되는 테마
     * - 진한 초록, 나무, 편안한 느낌
     */
    FOREST,

    /*
     * 바다 테마
     * - 새로 추가되는 테마
     * - 파랑, 청록, 시원한 느낌
     */
    OCEAN,

    /*
     * 노을 테마
     * - 새로 추가되는 테마
     * - 주황, 분홍, 보라가 섞인 감성적인 느낌
     */
    SUNSET,


    // 아래 4개는 예전 테마 값. 일단 대기
    // 커플용 저금통
    COUPLE,

    // 친구용 저금통
    FRIEND,

    // 가족용 저금통
    FAMILY,

    // 사용자가 직접 커스텀해서 만든 저금통
    CUSTOM
}